CREATE TABLE product (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 company_id BIGINT NOT NULL REFERENCES company(id),
 sku VARCHAR(100) NOT NULL,
 name VARCHAR(255) NOT NULL,
 category VARCHAR(255),
 preferred_supplier_id BIGINT,
 version INTEGER NOT NULL DEFAULT 1 CHECK(version>0),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(company_id,sku), UNIQUE(company_id,id)
);
CREATE TABLE inventory (
 product_id BIGINT PRIMARY KEY,
 company_id BIGINT NOT NULL,
 quantity INTEGER NOT NULL DEFAULT 0 CHECK(quantity>=0),
 version INTEGER NOT NULL DEFAULT 1 CHECK(version>0),
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(company_id,product_id) REFERENCES product(company_id,id)
);
CREATE TABLE sale (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 company_id BIGINT NOT NULL,
 product_id BIGINT NOT NULL,
 sale_date DATE NOT NULL,
 quantity INTEGER NOT NULL CHECK(quantity>=0),
 version INTEGER NOT NULL DEFAULT 1 CHECK(version>0),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(company_id,product_id) REFERENCES product(company_id,id),
 UNIQUE(company_id,product_id,sale_date)
);
CREATE INDEX sale_company_date ON sale(company_id,sale_date);
CREATE INDEX product_company_name ON product(company_id,name,id);
